"""One bounded nationwide day-link source probe, no source rows in logs.

Uses REAL Kdreams public calendar, meeting racecards and SHA ledger.
Does not invent links, scrape hidden APIs, or imply all registered races
are actually linked. No real forecasts/results are generated by this check.
"""
from __future__ import annotations

from pathlib import Path
from datetime import datetime,timezone
import json

from scripts import keirin_discover_public_race_links as discover
from scripts import keirin_capture_public_two_sources as capture
from scripts.keirin_nationwide_auto_forecast import registered_race_ids

REGISTRY=(Path(__file__).resolve().parents[1]/
          "docs/evidence/2026-11-18/keirin_all79_nationwide_AB_registered_v1.json")


def main():
    ids=registered_race_ids(json.loads(REGISTRY.read_text(encoding="utf-8")))
    try:
        out=discover.discover(
            day_jst="2026-11-18",registered_ids=ids,max_meetings=8)
        response={k:out[k] for k in (
            "schema","day_jst","registered_race_count",
            "candidate_race_count","unlinked_registered_race_count",
            "meetings_linked_in_calendar",
            "meeting_racecard_pages_attempted","source_errors",
            "all_races_linked","unlinked_races_are_HOLD",
            "source_pages_observed_from_live_HREFs_only")}
        response["real_AB_generated"]=0
        response["no_provider_private_HTML_or_rider_values_in_log"]=True
        return response
    except (capture.SourceCaptureError,discover.DayLinksError,ValueError,
            TypeError,KeyError,OSError):
        return {"state":"HOLD_KDREAMS_PUBLIC_DAY_LINKS_NOT_AVAILABLE",
                "real_AB_generated":0,"unlinked_races_are_HOLD":True}

if __name__=="__main__":
    print(json.dumps(main(),sort_keys=True))
