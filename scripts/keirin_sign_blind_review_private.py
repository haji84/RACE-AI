"""Offline owner-private signing of a completed, prediction-blind review.

Two independently designated reviewers sign different source-frame annotations
using their OWN Ed25519 private keys. No pre-existing key is generated by this
tool. The owner must independently authenticate both keys and packet challenges
through the existing keirin_signed_blind_review_gate. Signing is NOT proof that
the review was independent or correct; frame/truth adjudication remains separate.
Never send signer keys, reviewed boxes or plaintext video to public GitHub.
"""
from __future__ import annotations

from argparse import ArgumentParser
from datetime import datetime, timezone
from hashlib import sha256
from pathlib import Path
import base64
import json
import os
import re

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

from race_ai.keirin_signed_blind_review_gate import (
    SCHEMA,canonical,timestamp,sha,
)
from race_ai.keirin_blind_rider_holdout_gate import (
    REVIEW_SCHEMA,digest,
)


class SignerError(ValueError):
    pass


def need(ok,code):
    if not ok:raise SignerError(code)


def private_file(path):
    p=Path(path)
    need(p.is_file() and not p.is_symlink() and
         (p.stat().st_mode&0o077)==0 and
         p.parent.is_dir() and
         (p.parent.stat().st_mode&0o077)==0,
         "PRIVATE_REVIEW_FILE_MUST_BE_OWNER_ONLY")
    return p


def sign_completed_private_review(*,review_file,packet_manifest_file,
                                  private_key_file,preissued_challenge_sha256,
                                  output_file,clock_now=None):
    """Read *completed* private review, bind to exact blind packet; sign once.

    This helper deliberately does not load the detector's proposal JSON.
    Reviewers must not see candidate boxes or guessed car numbers.
    """
    review_path=private_file(review_file)
    packet_path=private_file(packet_manifest_file)
    key_path=private_file(private_key_file)
    dest=Path(output_file)
    need(dest.parent.is_dir() and
         (dest.parent.stat().st_mode&0o077)==0 and
         not dest.exists() and not dest.is_symlink(),
         "REVIEW_SIGNATURE_MUST_BE_PRIVATE_CREATE_ONCE")
    need(sha(preissued_challenge_sha256),
         "OWNER_PREISSUED_CHALLENGE_REQUIRED")
    raw=review_path.read_bytes()
    need(0<len(raw)<=5_000_000,"REVIEW_FILE_UNEXPECTED_SIZE")
    review=json.loads(raw)
    packet_raw=packet_path.read_bytes()
    need(0<len(packet_raw)<=5_000_000,"BLIND_PACKET_MANIFEST_SIZE_INVALID")
    packet=json.loads(packet_raw)
    need(type(packet) is dict and
         packet.get("schema")=="RACE_AI_KEIRIN_PRIVATE_BLIND_REVIEW_PACKET_V1" and
         packet.get("does_not_contain_model_predictions_or_rider_labels") is True,
         "ONLY_FROZEN_UNLABELED_BLIND_PACKET_ADMITTED")
    need(type(review) is dict and review.get("schema")==REVIEW_SCHEMA and
         review.get("reviewer_id")==packet.get("reviewer_id") and
         review.get("race_id")==packet.get("race_id") and
         review.get("recording_sha256")==packet.get("recording_sha256") and
         review.get("proposal_sha256")==packet.get("proposal_sha256") and
         review.get("independent_source_frame_read") is True and
         sha(review.get("review_sha256")) and
         review["review_sha256"]==digest({
             k:v for k,v in review.items() if k!="review_sha256"}),
         "BLIND_COMPLETED_REVIEW_SHA_OR_SOURCE_MISMATCH")
    need(type(packet.get("frames")) is list and
         type(review.get("frames")) is list and
         len(packet["frames"])==len(review["frames"]) and
         len(review["frames"])>0,
         "BLIND_PACKET_REVIEW_FRAME_COUNT_MISMATCH")
    for original,graded in zip(packet["frames"],review["frames"]):
        need(type(original) is dict and type(graded) is dict and
             graded.get("frame_sha256")==original.get("frame_sha256") and
             graded.get("exhaustive_visible_targets") is True and
             type(graded.get("annotations")) is list,
             "ALL_UNBLINDED_FRAME_LABELS_MUST_BE_COMPLETE")
    now=clock_now() if callable(clock_now) else datetime.now(timezone.utc)
    need(isinstance(now,datetime) and now.utcoffset() is not None,
         "SIGNER_AWARE_CLOCK_REQUIRED")
    signed_at=now.isoformat()
    need(timestamp(signed_at)>=timestamp(review.get("reviewed_at")),
         "REVIEW_CANNOT_BE_SIGNED_BEFORE_COMPLETION")
    pem=key_path.read_bytes()
    need(len(pem)<=5000,"PRIVATE_SIGNING_KEY_UNEXPECTED_SIZE")
    try:key=serialization.load_pem_private_key(pem,password=None)
    except (TypeError,ValueError):
        raise SignerError("REVIEWER_SIGNING_KEY_UNREADABLE") from None
    need(isinstance(key,Ed25519PrivateKey),"INDEPENDENT_ED25519_SIGNER_REQUIRED")
    body={
        "schema":SCHEMA,
        "reviewer_id":review["reviewer_id"],
        "race_id":review["race_id"],
        "recording_sha256":review["recording_sha256"],
        "proposal_sha256":review["proposal_sha256"],
        "review_sha256":review["review_sha256"],
        "packet_manifest_sha256":sha256(packet_raw).hexdigest(),
        "preissued_challenge_sha256":preissued_challenge_sha256,
        "signed_at":signed_at,
    }
    body["signature_b64"]=base64.b64encode(
        key.sign(canonical(body))).decode("ascii")
    payload=canonical(body)+b"\n"
    flags=os.O_WRONLY|os.O_CREAT|os.O_EXCL|getattr(os,"O_NOFOLLOW",0)
    with os.fdopen(os.open(dest,flags,0o600),"wb") as f:
        f.write(payload);f.flush();os.fsync(f.fileno())
    need(dest.read_bytes()==payload,"PRIVATE_REVIEW_SIGNATURE_READBACK_FAILED")
    return {
        "signature_file_sha256":sha256(payload).hexdigest(),
        "reviewer_signature_created":True,
        "public_GitHub_has_no_private_signer_key":True,
        "reviewer_identity_independently_verified":False,
        "human_source_truth_independently_adjudicated":False,
        "ready_to_submit_for_existing_holdout_gate":True,
        "formal_phase_score_automatically_updated":False,
    }


def main():
    cli=ArgumentParser()
    cli.add_argument("--review",required=True,type=Path)
    cli.add_argument("--blind-packet-manifest",required=True,type=Path)
    cli.add_argument("--reviewer-private-key",required=True,type=Path)
    cli.add_argument("--owner-challenge-sha256",required=True)
    cli.add_argument("--signature-output",required=True,type=Path)
    args=cli.parse_args()
    result=sign_completed_private_review(
        review_file=args.review,
        packet_manifest_file=args.blind_packet_manifest,
        private_key_file=args.reviewer_private_key,
        preissued_challenge_sha256=args.owner_challenge_sha256,
        output_file=args.signature_output)
    print(json.dumps(result,sort_keys=True))


if __name__=="__main__":
    main()
